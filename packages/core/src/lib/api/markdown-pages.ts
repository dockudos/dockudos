import { escapeMdx, escapeParagraphs, fence, yamlString } from './text.ts';

export interface PageMeta {
  title: string;
  description?: string;
  source: string;
  kind: string;
  group?: string;
  order: number;
  /** Shown in the sidebar instead of the title. */
  sidebarTitle?: string;
}

/** A generated page of plain Markdown. Text from the spec goes through `escapeMdx`, so it cannot break the page. */
export function markdownPage(meta: PageMeta, body: string): string {
  return `---
title: ${yamlString(meta.title)}
${meta.description ? `description: ${yamlString(meta.description)}\n` : ''}${meta.sidebarTitle ? `sidebarTitle: ${yamlString(meta.sidebarTitle)}\n` : ''}api:
  source: ${yamlString(meta.source)}
  kind: ${yamlString(meta.kind)}
${meta.group ? `  group: ${yamlString(meta.group)}\n` : ''}  order: ${meta.order}
---

{/* Generated by \`dockudos generate\`. Changes are overwritten. */}

${body.trim()}
`;
}

/** A table whose cells are escaped. Returns an empty string for no rows. */
export function table(head: string[], rows: string[][]): string {
  if (!rows.length) return '';
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map((c) => escapeMdx(c)).join(' | ')} |`),
  ].join('\n');
}

export const code = (text: string) => `\`${text.replaceAll('`', "'")}\``;
export { escapeMdx, escapeParagraphs, fence };
